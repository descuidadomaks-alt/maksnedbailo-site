// Encode one replacement into a new folder; originals and previous releases survive.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const [id, input] = process.argv.slice(2);
if (!id || !input) throw Error('Usage: node scripts/prepare-careless-video.mjs hero|clip-2..clip-9 source.mp4');
const manifestPath = path.resolve('public/careless/media.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (id !== 'hero' && manifest.cinema.master) throw Error('The journey now uses one master film. Replace the original source in your media folder, then run scripts/prepare-careless-film.mjs source-folder unique-release. The manifest retains shot order, crops, timing and cues.');
const clip = id === 'hero' ? manifest.cinema.hero : manifest.cinema.journey.find(item => item.id === id);
if (!clip || !fs.statSync(input).isFile()) throw Error('Unknown clip or missing source');
const run = (tool, args) => { const result = spawnSync(tool, args, { encoding: 'utf8', windowsHide: true }); if (result.status !== 0) throw Error(result.stderr || `${tool} unavailable`); return result.stdout; };
const probe = file => JSON.parse(run('ffprobe', ['-v','error','-show_format','-show_streams','-of','json',file]));
const source = probe(input);
if (!source.streams.some(s => s.codec_type === 'video')) throw Error('Source has no video');
const release = `replacement-${Date.now()}`;
const folder = path.resolve('public/careless/video', release);
fs.mkdirSync(folder, { recursive: true });
const output = path.join(folder, `${id}.mp4`);
const keyframes = id === 'hero' ? '48' : '1';
run('ffmpeg', ['-hide_banner','-loglevel','error','-i',path.resolve(input),'-an','-vf','scale=min(864\\,iw):-2','-r','24','-c:v','libx264','-preset','fast','-crf','24','-g',keyframes,'-keyint_min',keyframes,'-bf','0','-pix_fmt','yuv420p','-movflags','+faststart','-threads','2','-n',output]);
const encoded = probe(output);
const duration = Number(encoded.format.duration);
const start = Math.min(clip.inPoint || 0, Math.max(0, duration - .1));
for (const [suffix, time] of [['first', start], ['last', Math.max(0, duration - .06)]]) run('ffmpeg', ['-hide_banner','-loglevel','error','-ss',String(time),'-i',output,'-frames:v','1','-c:v','libwebp','-quality','80','-n',path.join(folder, `${id}-${suffix}.webp`)]);
const url = `/careless/video/${release}/${id}`;
Object.assign(clip, { src: `${url}.mp4`, poster: `${url}-first.webp`, duration });
if (id !== 'hero') Object.assign(clip, { endPoster: `${url}-last.webp`, sourceFile: path.basename(input), inPoint: start, outPoint: duration - .05, fps: 24 });
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
console.log(`Prepared ${id}: ${(fs.statSync(output).size / 1e6).toFixed(2)} MB. Inspect crops, trims, transitions and device seeking before deploying.`);
